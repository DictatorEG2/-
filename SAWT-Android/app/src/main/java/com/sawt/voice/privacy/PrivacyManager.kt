    /** النص الذي يُحفظ في سجل الأوامر: لا يُحفظ ما قاله المستخدم عند الكتابة أو الأرقام. */
    fun historyText(command: Command, raw: String): String = when (command) {
        is Command.Type, is Command.Call, is Command.CallContact, is Command.WhatsAppChat, is Command.WhatsAppContact -> "«محتوى محجوب لحماية خصوصيتك»"
        else -> raw.take(120)
    }

    suspend fun clearHistory() {
        AppGraph.db.historyDao().clear()
    }

